#!/usr/bin/env python3
"""Derive the website hero lockup from the sanctioned cinematic lockup.

Source:  docs/brand/assets/lockup-cinematic.svg  (generated by build-logos.py)
Output:  apps/web/public/brand/lockup-hero.svg

The cinematic lockup ships on its own stage (forest-night ground, emerald +
lantern glows, vignette). On the website the hero section (`.ph-stage`)
already paints that stage, and the brand rule is "one key glow per layout",
so the web variant:

  * drops the four stage layers (transparent background),
  * drops the byline and tagline outlines — the page renders those as real
    text (`.ph-kicker` byline, italic tagline) so they stay readable,
    selectable and indexable,
  * crops the viewBox to the emblem + PERPUSTAKAAN + extruded HATI.

Everything else (outlines, foil gradients, bevel filters, 14px extrusion,
contact + ambient shadows) is copied byte for byte. Stdlib only.

Run after build-logos.py:
    uv run --no-project python packages/brand-tools/build-web-lockup.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs/brand/assets/lockup-cinematic.svg"
OUT = ROOT / "apps/web/public/brand/lockup-hero.svg"

# Mark bounds measured from the outlines (x 337-1264, y 120-824) plus room
# for the blurred ambient shadow under HATI.
VIEWBOX = "300 80 1000 780"

STAGE = re.compile(
    r'\n  <rect width="1600" height="1000" fill="#07140d"/>'
    r'\n  <ellipse[^\n]*\n  <ellipse[^\n]*'
    r'\n  <rect width="1600" height="1000" fill="url\(#phl-vignette\)"/>'
)
FLANK = re.compile(r'\n  <path fill="#c9a86a" d="M381[^\n]*')
BYLINE_TAGLINE = re.compile(r'\n  <path fill="#e9cea2"[^\n]*\n  <path fill="#a7d3b6"[^\n]*')


def derive(svg: str) -> str:
    for name, pattern in (("stage", STAGE), ("flank", FLANK), ("byline/tagline", BYLINE_TAGLINE)):
        svg, n = pattern.subn("", svg, count=1)
        if n != 1:
            raise SystemExit(f"build-web-lockup: could not find the {name} layer; "
                             "has build-logos.py changed the lockup layout?")
    svg = svg.replace(
        'viewBox="0 0 1600 1000" width="1600" height="1000"',
        f'viewBox="{VIEWBOX}" width="1000" height="780"', 1)
    svg = svg.replace('aria-label="Perpustakaan Hati cinematic lockup"',
                      'aria-label="Perpustakaan Hati"', 1)
    return svg.replace(
        "Use: Threads/IG headers, store hero, video opener, posters.",
        "WEB VARIANT (build-web-lockup.py): transparent, no byline/tagline,\n"
        "    cropped. Do not edit by hand; regenerate from the source lockup.", 1)


def main() -> int:
    OUT.write_text(derive(SRC.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
